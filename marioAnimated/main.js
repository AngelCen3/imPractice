  class Sprite {
    constructor({ animations = [], data }) {
      this.animations = animations;
      this.animation = "walk";
      this.frame = {};
      this.frameIndex = -1;
      this.data = data;
    }
  
    advance() {
      if (frames % 8 === 0) {
        this.frameNames = this.animations[this.animation].frames;
  
        if (this.frameIndex + 1 >= this.frameNames.length) {
          this.frameIndex = 0;
        } else {
          this.frameIndex++;
        }
        this.frame = this.data.frames[this.frameNames[this.frameIndex]].frame;
      }
    }
  }
  
  class Character extends Sprite {
    constructor(imageURL, spriteObject, x, y, w, h) {
      super(spriteObject);
      this.x = x || 200;
      this.y = y || 200;
      this.w = w || 50;
      this.h = h || 50;
      this.image = new Image();
      this.image.src = imageURL;
    }
  
    draw() {
      this.advance();
      ctx.drawImage(
        this.image,
        this.frame.x,
        this.frame.y,
        this.frame.w,
        this.frame.h,
        this.x,
        this.y,
        this.w,
        this.h
      );
    }
  }
  
